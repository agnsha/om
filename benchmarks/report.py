"""Write RESULTS.md from speed/results.json, tokens/results.json and
bugrate/results.json. Run after the three benchmarks (see README.md)."""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
load = lambda p: json.load(open(os.path.join(HERE, p)))
speed, tokens, bugs = load("speed/results.json"), load("tokens/results.json"), load("bugrate/results.json")
L = []
w = L.append

w("# Results\n")
w("Generated by `report.py`. Raw numbers are in `speed/results.json`, `tokens/results.json` and `bugrate/results.json`.\n")

m = speed["meta"]
w("## Runtime speed\n")
w(f"Median of {m['runs']} runs (Python: 1 run), wall time in seconds including process start. "
  f"Machine: {m['machine']}, {m['os']}. {m['om']}; {m['rustc']}; Python {m['python']}.\n")
w("| Program | Om | Rust `-O` | Rust `-O` + overflow checks | Python | Om vs Rust |")
w("|---|---:|---:|---:|---:|---:|")
for r in speed["results"]:
    t = r["run_s"]
    w(f"| {r['program']} ({r['arg']}) | {t['om']:.3f} | {t['rs']:.3f} | {t['rs_checked']:.3f} | {t['py']:.2f} | {t['om'] / t['rs']:.1f}x slower |")
geo = lambda k: __import__("math").prod(r["run_s"][k] for r in speed["results"]) ** (1 / len(speed["results"]))
w(f"\nGeometric mean: Om is **{geo('om') / geo('rs'):.1f}x slower than Rust** "
  f"({geo('om') / geo('rs_checked'):.1f}x slower than Rust with overflow checks on) "
  f"and **{geo('py') / geo('om'):.0f}x faster than Python**.\n")
w("| Build time (s) | " + " | ".join(r["program"] for r in speed["results"]) + " |")
w("|---|" + "---:|" * len(speed["results"]))
w("| `om build` | " + " | ".join(f"{r['build_s']['om']:.2f}" for r in speed["results"]) + " |")
w("| `rustc -O` | " + " | ".join(f"{r['build_s']['rs']:.2f}" for r in speed["results"]) + " |\n")

NAMES = {"sonnet": "Claude Sonnet", "haiku": "Claude Haiku"}
w("## Tokens\n")
w("Counted with real tokenizers (`o200k_base`, used by GPT-4o, and `cl100k_base`, used by GPT-4) through js-tiktoken. "
  "Claude's tokenizer is not public. Lower is better.\n")
w("| Program set | Om | Rust | Python | Om / Rust | Om / Python |")
w("|---|---:|---:|---:|---:|---:|")
names = {"speed": "Speed programs (hand-written)", "budget": "Token-budget programs (hand-written, `bench/tokens`)"}
for k, s in tokens["sets"].items():
    t = s["total_o200k"]
    label = names.get(k, f"Written by {NAMES.get(k[4:], k[4:])} (tasks all three passed)")
    w(f"| {label}, n={len(s['rows'])} | {t['om']} | {t['rust']} | {t['python']} | {t['om'] / t['rust']:.2f} | {t['om'] / t['python']:.2f} |")
w(f"\nAn LLM has never seen Om, so it needs the Om guide in its context once per session: "
  f"**{tokens['om_guide']['o200k']} tokens** (o200k). Rust and Python need nothing.\n")

w("## Bug rate\n")
w("Each model wrote all 12 tasks in each language from the same task text, in one shot with no compiler feedback "
  "(Om attempts also got the Om guide). A task passes if it builds, runs and prints exactly the expected output.\n")
w("| Model | Om | Rust | Python |")
w("|---|---:|---:|---:|")
NAMES = {"sonnet": "Claude Sonnet", "haiku": "Claude Haiku"}
for model, r in bugs.items():
    cells = []
    for lang in ("om", "rust", "python"):
        rows = r.get(lang, {})
        n = sum(x["outcome"] == "pass" for x in rows.values())
        cells.append(f"{n}/{len(rows)}" if rows else "-")
    w(f"| {NAMES.get(model, model)} | " + " | ".join(cells) + " |")
w("\nFailures:\n")
any_fail = False
for model, r in bugs.items():
    for lang, rows in r.items():
        for task, x in rows.items():
            if x["outcome"] != "pass":
                any_fail = True
                first = x.get("detail", "").splitlines()[0] if x.get("detail") else ""
                w(f"- {model} / {lang} / `{task}`: {x['outcome']}. `{first[:160]}`")
if not any_fail:
    w("- none")
w("")
w(open(os.path.join(HERE, "findings.md")).read())
open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(L) + "\n")
print("wrote RESULTS.md")
